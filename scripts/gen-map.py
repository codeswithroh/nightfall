# Generates the arena map (4-way symmetric) for both the Rust program and the web client.
# Legend: . grass  T tree(solid)  # cobblestone(solid)  " tall grass(hides you)  ~ water(blocks movement)
#         S spawn point (grass)   C chest candidate (grass)
import json, pathlib

HALF = [
    "TTTTTTTTTTTT",
    "TS....\"\"..T.",
    "T.##..\"\"....",
    "T.#C......#.",
    "T....TT...#.",
    "T\"\"..T..~~..",
    "T\"\".....~~..",
    "T...##......",
    "T.S.#..C.\"\".",
    "T......##\"\".",
    "T.T.......#.",
    "T...\"\"..C...",
]
top = [row + row[::-1] for row in HALF]
rows = top + top[::-1]
assert len(rows) == 24 and all(len(r) == 24 for r in rows)

TILE = {".": 0, "S": 0, "C": 0, "T": 1, "#": 1, '"': 2, "~": 3}
tiles = [TILE[c] for r in rows for c in r]
spawns = [(x, y) for y, r in enumerate(rows) for x, c in enumerate(r) if c == "S"]
chests = [(x, y) for y, r in enumerate(rows) for x, c in enumerate(r) if c == "C"]
assert len(spawns) == 8 and len(chests) == 12, (len(spawns), len(chests))

root = pathlib.Path(__file__).resolve().parent.parent
(root / "shared/map.json").write_text(json.dumps({"rows": rows, "spawns": spawns, "chests": chests}, indent=1))

def arr(pairs):
    return ", ".join(f"({x}, {y})" for x, y in pairs)

rs = f"""// @generated by scripts/gen-map.py — do not edit by hand.
pub const MAP_W: usize = 24;
pub const MAP_H: usize = 24;
/// 0 grass, 1 solid (tree / stone), 2 tall grass (blocks sight), 3 water (blocks movement)
pub const TILES: [u8; MAP_W * MAP_H] = {tiles};
pub const SPAWNS: [(u8, u8); 8] = [{arr(spawns)}];
pub const CHEST_SPOTS: [(u8, u8); 12] = [{arr(chests)}];
"""
(root / "programs/nightfall/src/map.rs").write_text(rs)
print("\n".join(rows))
