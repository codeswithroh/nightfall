# Generates the arena maps (each 4-way symmetric) for both the Rust program and the web client.
# Legend: . floor   T tree/pillar (solid)   # wall (solid)   " tall grass (hides you)   ~ water/ice/lava (blocks movement)
#         S spawn point   C chest spot
import json, pathlib
from collections import deque

MAPS = [
    {
        "name": "Moonlit Woods",
        "half": [
            "TTTTTTTTTTTT",
            "TS....\"\"..T.",
            "T.##..\"\"....",
            "T.#C......#.",
            "T....TT...#.",
            "T\"\"..T..~~..",
            "T\"\".....~~..",
            "T...##......",
            "T.S.#..C.\"\".",
            "T......##\"\".",
            "T.T.......#.",
            "T...\"\"..C...",
        ],
    },
    {
        "name": "Frostpeak Ruins",
        "half": [
            "TTTTTTTTTTTT",
            "TS....\"...#.",
            "T.##..\"..C#.",
            "T.#.......#.",
            "T...~~~.....",
            "T\"..~~~..##.",
            "T\"......\"...",
            "T.C..#...\".~",
            "T....#...\".~",
            "T.S.....~~..",
            "T..##..C~~..",
            "T\"..........",
        ],
    },
    {
        "name": "Ember Keep",
        "half": [
            "TTTTTTTTTTTT",
            "TS..#...#...",
            "T...#.C.#.##",
            "T.###...#...",
            "T.....~~~...",
            "T#.##.~~~.#.",
            "T\"..#.....#.",
            "T\"..#.##..#.",
            "T.S.....#...",
            "T.##.C..#.##",
            "T..#..###...",
            "T.C..\"......",
        ],
    },
]

TILE = {".": 0, "S": 0, "C": 0, "T": 1, "#": 1, '"': 2, "~": 3}
root = pathlib.Path(__file__).resolve().parent.parent
out = []
rs = ["// @generated by scripts/gen-map.py — do not edit by hand.",
      "pub const MAP_W: usize = 24;", "pub const MAP_H: usize = 24;", "pub const MAP_COUNT: usize = 3;", "",
      "/// tiles: 0 floor, 1 solid (tree / wall), 2 tall grass (blocks sight), 3 water/lava (blocks movement)",
      "pub struct MapDef {", "    pub tiles: [u8; MAP_W * MAP_H],", "    pub spawns: [(u8, u8); 8],", "    pub chests: [(u8, u8); 12],", "}", "",
      "pub const MAPS: [MapDef; MAP_COUNT] = ["]
for m in MAPS:
    half = m["half"]
    assert len(half) == 12 and all(len(r) == 12 for r in half), (m["name"], [len(r) for r in half])
    top = [row + row[::-1] for row in half]
    rows = top + top[::-1]
    tiles = [TILE[c] for r in rows for c in r]
    spawns = [(x, y) for y, r in enumerate(rows) for x, c in enumerate(r) if c == "S"]
    chests = [(x, y) for y, r in enumerate(rows) for x, c in enumerate(r) if c == "C"]
    assert len(spawns) == 8 and len(chests) == 12, (m["name"], len(spawns), len(chests))
    # Everything walkable must be reachable, and the final circle (centre 2x2) must be walkable.
    walk = {(x, y) for y, r in enumerate(rows) for x, c in enumerate(r) if TILE[c] in (0, 2)}
    for c in [(11, 11), (12, 11), (11, 12), (12, 12)]:
        assert c in walk, (m["name"], "centre blocked", c)
    seen, q = {spawns[0]}, deque([spawns[0]])
    while q:
        x, y = q.popleft()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            n = (x + dx, y + dy)
            if n in walk and n not in seen:
                seen.add(n); q.append(n)
    assert seen == walk, (m["name"], "unreachable", sorted(walk - seen)[:5])
    out.append({"name": m["name"], "rows": rows, "spawns": spawns, "chests": chests})
    pairs = lambda ps: ", ".join(f"({x}, {y})" for x, y in ps)
    rs.append(f"    // {m['name']}")
    rs.append(f"    MapDef {{ tiles: {tiles}, spawns: [{pairs(spawns)}], chests: [{pairs(chests)}] }},")
rs.append("];")
(root / "shared/map.json").write_text(json.dumps({"maps": out}, indent=1))
(root / "programs/nightfall/src/map.rs").write_text("\n".join(rs) + "\n")
for m in out:
    print(m["name"]); print("\n".join(m["rows"])); print()
